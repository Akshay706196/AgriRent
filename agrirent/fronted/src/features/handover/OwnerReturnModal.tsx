import React, { useState } from 'react';
import { ShieldAlert, KeyRound, Wrench } from 'lucide-react';
import { Modal } from '../../components/ui/Modal';
import { Button } from '../../components/ui/Button';
import { PinInput } from '../../components/ui/PinInput';
import { handoverApi } from '../../api/handover.api';
import { ConditionReport } from '../../api/types';
import { useIdempotencyKey } from '../../hooks/useIdempotencyKey';
import { useNotification } from '../../context/NotificationContext';
import { ApiError } from '../../api/errors';

interface OwnerReturnModalProps {
  isOpen: boolean;
  onClose: () => void;
  bookingId: string;
  onSuccess: () => void;
}

export const OwnerReturnModal: React.FC<OwnerReturnModalProps> = ({
  isOpen,
  onClose,
  bookingId,
  onSuccess,
}) => {
  const [pin, setPin] = useState('');
  const [engineHours, setEngineHours] = useState<number>(135);
  const [fuelLevelPercent, setFuelLevelPercent] = useState<number>(85);
  const [cleanliness, setCleanliness] = useState<'EXCELLENT' | 'GOOD' | 'FAIR' | 'POOR'>('GOOD');
  const [notes, setNotes] = useState('');
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [errorCode, setErrorCode] = useState<string | null>(null);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);

  const { key: idempotencyKey, refreshKey } = useIdempotencyKey(`return-${bookingId}`);
  const { showNotification } = useNotification();

  const handleVerify = async (e: React.FormEvent) => {
    e.preventDefault();
    setErrorCode(null);
    setErrorMessage(null);

    if (pin.length !== 6) {
      setErrorMessage('Please enter the 6-digit return PIN provided by the renter.');
      return;
    }

    setIsSubmitting(true);
    try {
      const conditionReport: ConditionReport = {
        engineHours: Number(engineHours),
        fuelLevelPercent: Number(fuelLevelPercent),
        cleanliness,
        visualInspectionNotes: notes.trim() || 'Return inspection satisfactory.',
        photoUrls: [],
      };

      await handoverApi.verifyReturn(bookingId, pin, conditionReport, idempotencyKey);
      showNotification('success', 'Return PIN verified! Equipment has been marked RETURNED.');
      onSuccess();
      onClose();
    } catch (err: any) {
      if (err instanceof ApiError) {
        setErrorCode(err.code);
        if (err.status === 423 || err.code === 'PIN_LOCKED') {
          setErrorMessage('PIN attempts exceeded and locked (423). Please ask the renter to generate a new PIN.');
        } else if (err.code === 'INVALID_PIN') {
          setErrorMessage('Invalid PIN. Please re-check the 6 digits.');
        } else if (err.code === 'PIN_EXPIRED') {
          setErrorMessage('This PIN has expired. Ask the renter to click "Generate New Return PIN".');
        } else {
          setErrorMessage(err.friendlyMessage);
        }
      } else {
        setErrorMessage(err.message || 'Failed to verify return PIN.');
      }
      refreshKey();
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <Modal isOpen={isOpen} onClose={onClose} title="Verify Machinery Return PIN">
      <form onSubmit={handleVerify} className="space-y-5">
        <div className="bg-amber-50 border border-amber-200 rounded-2xl p-4 text-xs text-amber-900 flex items-start space-x-3">
          <KeyRound className="w-5 h-5 text-amber-700 flex-shrink-0 mt-0.5" />
          <div>
            <p className="font-bold">Enter Renter's Return PIN</p>
            <p className="mt-0.5">
              Enter the 6-digit PIN generated by the renter upon returning the machine to stop the rental timer.
            </p>
          </div>
        </div>

        {/* 6-box PIN input */}
        <div>
          <label className="block text-xs font-semibold text-earth-700 uppercase tracking-wider mb-2 text-center">
            Renter's Return PIN
          </label>
          <PinInput
            value={pin}
            onChange={setPin}
            disabled={isSubmitting}
            hasError={!!errorCode}
          />
        </div>

        {/* Distinct Error Message */}
        {errorMessage && (
          <div
            className={`p-3.5 rounded-xl text-xs flex items-start ${
              errorCode === 'PIN_LOCKED'
                ? 'bg-purple-50 border border-purple-300 text-purple-900 font-medium'
                : 'bg-red-50 border border-red-200 text-red-700'
            }`}
          >
            <ShieldAlert className="w-4 h-4 mr-2 flex-shrink-0 mt-0.5" />
            <span>{errorMessage}</span>
          </div>
        )}

        {/* Return Condition Report */}
        <div className="border-t border-earth-200 pt-4 space-y-3">
          <h4 className="text-xs font-bold text-earth-800 uppercase tracking-wider flex items-center">
            <Wrench className="w-3.5 h-3.5 mr-1.5 text-earth-600" />
            Return Condition Inspection
          </h4>

          <div className="grid grid-cols-2 gap-3 text-xs">
            <div>
              <label className="block font-semibold text-earth-700 mb-1">Return Engine Hours</label>
              <input
                type="number"
                value={engineHours}
                onChange={(e) => setEngineHours(Number(e.target.value))}
                className="w-full px-3 py-2 bg-earth-50 border border-earth-300 rounded-lg text-earth-900"
              />
            </div>
            <div>
              <label className="block font-semibold text-earth-700 mb-1">Fuel Level (%)</label>
              <input
                type="number"
                min="0"
                max="100"
                value={fuelLevelPercent}
                onChange={(e) => setFuelLevelPercent(Number(e.target.value))}
                className="w-full px-3 py-2 bg-earth-50 border border-earth-300 rounded-lg text-earth-900"
              />
            </div>
          </div>

          <div>
            <label className="block text-xs font-semibold text-earth-700 mb-1">Cleanliness</label>
            <select
              value={cleanliness}
              onChange={(e) => setCleanliness(e.target.value as any)}
              className="w-full px-3 py-2 bg-earth-50 border border-earth-300 rounded-lg text-xs text-earth-900"
            >
              <option value="EXCELLENT">Clean / Washed</option>
              <option value="GOOD">Good / Normal Wear</option>
              <option value="FAIR">Fair / Dirty</option>
              <option value="POOR">Poor / Damaged or Excessive Mud</option>
            </select>
          </div>

          <div>
            <label className="block text-xs font-semibold text-earth-700 mb-1">Inspection Notes</label>
            <input
              type="text"
              value={notes}
              onChange={(e) => setNotes(e.target.value)}
              placeholder="Record any dents, blade wear, or fuel differences"
              className="w-full px-3 py-2 bg-earth-50 border border-earth-300 rounded-lg text-xs text-earth-900"
            />
          </div>
        </div>

        <div className="flex justify-end space-x-3 pt-2">
          <Button type="button" variant="outline" onClick={onClose} disabled={isSubmitting}>
            Cancel
          </Button>
          <Button
            type="submit"
            variant="primary"
            isLoading={isSubmitting}
            disabled={pin.length !== 6}
          >
            Verify Return PIN
          </Button>
        </div>
      </form>
    </Modal>
  );
};
